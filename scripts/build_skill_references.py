#!/usr/bin/env python3
"""Generate evidence reference files for the agent skills in skills/ from the indexed graph.

For each skill, writes skills/<skill>/references/episodes.md containing, per source episode:
title + YouTube link, graph techniques citing it (rules / anti-patterns when available),
prescriptive quotes pulled from the official English transcript, and graph-linked visual
references (local WebP contact sheets + exact YouTube timestamps).

SKILL.md files are hand-authored; only references/ is generated.
"""

from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import typer
from rich.console import Console

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lib.config import GRAPH_JSON_PATH, ROOT_DIR, TRANSCRIPTS_DIR, format_timestamp, load_manifest

console = Console()
app = typer.Typer(add_completion=False)

SKILLS_DIR = ROOT_DIR / "skills"


def _codes(spec: str) -> list[str]:
    """Expand 'B01-B29,D13' into explicit episode codes."""
    out: list[str] = []
    for part in spec.split(","):
        part = part.strip()
        m = re.fullmatch(r"([A-Z]+)(\d+)-\1?(\d+)", part)
        if m:
            prefix, a, b = m.group(1), int(m.group(2)), int(m.group(3))
            out.extend(f"{prefix}{i:02d}" for i in range(a, b + 1))
        elif part:
            out.append(part)
    return out


# Skill -> source episodes (overlap is intentional where a lesson spans two areas).
SKILL_SOURCES: dict[str, str] = {
    "sakurai-game-essence": "B01-B29,C03,C17,C23,C24,C26,C29,D13,D14,D15,N06,N08",
    "sakurai-action-feel": "C01,C06,C09,C12,C15,D01-D05,D07,D08,D11,D18,G04,H05,I09,M01",
    "sakurai-attack-animation": "G01-G18,D04,D18,F11,F20",
    "sakurai-vfx-and-graphics": "H01-H11,F01-F20,C25,D05",
    "sakurai-audio-direction": "I01-I14",
    "sakurai-ui-ux": "J01-J15,C02,C10,C12,C13,C20,C21,C27,C28,C30,D06,D09,D12,D17",
    "sakurai-planning-and-specs": (
        "A04,A05,A06,A11,A14,A17,A21,B29,C04-C08,C11,C14,C16,C18,C19,C22,"
        "D10,D16,K02,K03,K06,N01-N12,S04"
    ),
    "sakurai-direction-and-teamwork": (
        "A01-A03,A07-A10,A12,A13,A15,A16,A18-A23,E01-E15,K01,K04,K05,K07,K08,K09,"
        "L01-L09,M12,M19"
    ),
}

CUES = re.compile(
    r"\b(should|shouldn't|must|don't|do not|never|always|important|key|make sure|need to|"
    r"recommend|try to|the trick|the point|essential|crucial|avoid|instead|rule|"
    r"that's why|so that|the goal|better to|best to|ideal|careful|frames?)\b",
    re.IGNORECASE,
)


def _quotes(text: str, limit: int = 5, max_words: int = 55) -> list[str]:
    sents = re.split(r"(?<=[.!?])\s+", text.replace("\n", " "))
    picked: list[str] = []
    for s in sents:
        s = s.strip()
        n = len(s.split())
        if 7 <= n <= max_words and CUES.search(s) and s not in picked:
            picked.append(s)
        if len(picked) >= limit:
            break
    return picked


@app.command()
def main() -> None:
    """Regenerate skills/*/references/episodes.md from graph.json + transcripts."""
    manifest = {e["code"]: e for e in load_manifest()}
    graph = json.loads(GRAPH_JSON_PATH.read_text(encoding="utf-8"))

    techs_by_ep: dict[str, list[dict]] = defaultdict(list)
    visuals_by_ep: dict[str, dict[str, dict]] = defaultdict(dict)
    for n in graph["nodes"]:
        if n.get("node_type") != "technique":
            continue
        for c in n.get("citations", []):
            techs_by_ep[c["episode_code"]].append(n)
        for v in n.get("visuals", []):
            visuals_by_ep[v["code"]][v["asset_id"]] = v

    for skill, spec in SKILL_SOURCES.items():
        skill_dir = SKILLS_DIR / skill
        if not (skill_dir / "SKILL.md").exists():
            console.print(f"[yellow]Skipping {skill}: SKILL.md missing[/yellow]")
            continue
        ref_dir = skill_dir / "references"
        ref_dir.mkdir(parents=True, exist_ok=True)

        lines = [
            f"# Source episodes for `{skill}`",
            "",
            "Generated by `scripts/build_skill_references.py` from `knowledge/graph.json` and the",
            "official English transcripts of *Masahiro Sakurai on Creating Games*. Quotes are the",
            "8-4 Ltd. localization recovered via OCR (minor OCR artifacts possible). Visual paths are",
            "relative to this file and exist when the full repository is cloned.",
            "",
        ]
        n_eps = n_vis = 0
        for code in _codes(spec):
            ep = manifest.get(code)
            if not ep:
                continue
            n_eps += 1
            title = re.sub(r"\s*\[[^\]]+\]\s*$", "", ep["title"]).strip()
            lines.append(f"## {code} — {title}")
            lines.append(
                f"*{ep['category_name']} · {format_timestamp(ep['duration_sec'])} · "
                f"[watch]({ep['url']})*"
            )
            lines.append("")

            for t in techs_by_ep.get(code, []):
                # Heuristic-mode techniques just mirror the episode title + raw transcript lines;
                # only LLM-extracted techniques carry distinct names and curated rules.
                if t["label"].strip().lower() == title.lower():
                    continue
                lines.append(f"**Technique:** {t['label']} — {t.get('summary', '')[:300]}")
                lines.extend(f"- ✅ {r}" for r in t.get("actionable_rules", [])[:4])
                lines.extend(f"- ❌ {a}" for a in t.get("anti_patterns", [])[:3])

            tr_path = TRANSCRIPTS_DIR / f"{ep['slug']}.json"
            if tr_path.exists():
                full = json.loads(tr_path.read_text(encoding="utf-8")).get("full_text", "")
                for q in _quotes(full):
                    lines.append(f"> {q}")
                    lines.append(">")
                if lines[-1] == ">":
                    lines.pop()

            vis = sorted(visuals_by_ep.get(code, {}).values(), key=lambda v: v["start_sec"])[:4]
            if vis:
                lines.append("")
                lines.append("Visual references:")
                for v in vis:
                    n_vis += 1
                    desc = v.get("visual_summary", "") if v.get("analysis_mode") == "gemini" else ""
                    desc = f" — {desc[:160]}" if desc else ""
                    lines.append(
                        f"- [{v['asset_type']} @ {format_timestamp(v['start_sec'])}]"
                        f"(../../../{v['local_path']}) · [YouTube]({v['youtube_url']}){desc}"
                    )
            lines.append("")

        (ref_dir / "episodes.md").write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
        console.print(f"[green]✓[/green] {skill}: {n_eps} episodes, {n_vis} visual refs")


if __name__ == "__main__":
    app()
